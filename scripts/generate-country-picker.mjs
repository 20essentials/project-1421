// Regenerates src/features/forms/country-flags.generated.ts: the Heart to Heart form's Location
// dropdown (updated via Form Schemas v4 PATCH to the full country list) stores the Italian country
// NAME as the option value, and the frontend needs that name's ISO 3166-1 alpha-2 code back to
// render a flag (twemoji CDN URL; Windows renders flag emoji as letter codes). Run:
//   node scripts/generate-country-picker.mjs
// The same names must stay in sync with the options the form holds in Wix (label === value).
import { writeFileSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
// The core file resolves "@/features/..." through the bundler, which Node cannot — extract the
// array literal instead of importing it.
const core = readFileSync(path.join(root, "src/features/forms/forms-address-core.ts"), "utf8");
const match = core.match(/export const COUNTRY_CODES(?::[^=]*)?= (\[[^\]]*\])/);
if (!match) throw new Error("COUNTRY_CODES not found in forms-address-core.ts");
const COUNTRY_CODES = JSON.parse(match[1]);

const dn = new Intl.DisplayNames(["it"], { type: "region" });
const byName = new Map();
const skipped = [];
for (const code of COUNTRY_CODES) {
  let name;
  try {
    name = dn.of(code);
  } catch {
    name = undefined;
  }
  if (!name || name === code) {
    skipped.push(code);
    continue;
  }
  if (byName.has(name)) {
    skipped.push(`${code} (dup of ${byName.get(name)})`);
    continue;
  }
  byName.set(name, code);
}

const rows = [...byName.entries()].sort((a, b) => a[0].localeCompare(b[0], "it"));

let out = "// Generated by scripts/generate-country-picker.mjs on " + new Date().toISOString().slice(0, 10) + "\n";
out += "// Italian country names (Intl.DisplayNames(\"it\")) -> ISO 3166-1 alpha-2 code, keyed by the exact\n";
out += "// value the Heart to Heart form's Location dropdown stores. The code feeds the flag lookup in\n";
out += "// choice-combobox-core.ts; labels not in the map (e.g. \"Altra destination\") render without a flag.\n";
out += "export const COUNTRY_CODES_BY_NAME: Record<string, string> = {\n";
for (const [name, code] of rows) out += `  ${JSON.stringify(name)}: ${JSON.stringify(code)},\n`;
out += "};\n";
writeFileSync(path.join(root, "src/features/forms/country-flags.generated.ts"), out);

console.log(`wrote ${rows.length} entries; skipped: ${skipped.join(", ") || "none"}`);
